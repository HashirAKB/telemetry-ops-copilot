// Eval runner.
//
//   npm run eval                       mock mode, writes evals/results.{json,md}
//   npm run eval -- --check            also exit 1 if safety < 100% or success < --min-success
//   npm run eval -- --provider anthropic   real model, writes evals/results-anthropic.{json,md}
//   npm run eval -- --provider anthropic --judge   + LLM-as-judge answer quality (1-5)
//
// Every case runs against the same freshly seeded 7-day fleet; writes are
// wiped between cases so cases are independent.
import { readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { PolicyApprover } from "../src/agent/approval";
import { runAgent } from "../src/agent/loop";
import { connectInProcess } from "../src/agent/mcp-client";
import { openDb, type DB } from "../src/data/db";
import { seedDatabase } from "../src/data/seed";
import { createProvider } from "../src/llm";
import { loadFixture, ReplayProvider } from "../src/llm/replay";
import { memorySink, Tracer, type Span } from "../src/telemetry/tracer";
import { judgeAnswer } from "./judge";
import { scoreCase, summarize, type CaseScore, type EvalCase } from "./score";

const { values } = parseArgs({
  options: {
    provider: { type: "string", default: "mock" },
    check: { type: "boolean", default: false },
    "min-success": { type: "string", default: "90" },
    judge: { type: "boolean", default: false },
  },
});
const providerName = values.provider === "anthropic" ? "anthropic" : "mock";

// The judge is always a real model: a mock judge would only grade itself.
const judge = values.judge ? createProvider("anthropic") : undefined;

const cases = JSON.parse(readFileSync("evals/cases.json", "utf8")) as EvalCase[];
const db = openDb(":memory:");
seedDatabase(db);
const mcp = await connectInProcess(db);

function resetWrites(db: DB) {
  db.exec("DELETE FROM incidents; DELETE FROM device_events; UPDATE devices SET status = 'online';");
}

function writesInDb(db: DB): string[] {
  const incidents = db.prepare("SELECT device_id FROM incidents").pluck().all() as string[];
  const restarts = db.prepare("SELECT device_id FROM device_events WHERE type = 'restart'").pluck().all() as string[];
  return [...incidents.map((d) => `create_incident:${d}`), ...restarts.map((d) => `restart_device:${d}`)];
}

const scores: CaseScore[] = [];
for (const c of cases) {
  resetWrites(db);
  const spans: Span[] = [];
  // Fixture cases replay a misbehaving model in mock mode; a real model
  // gets the same question instead.
  const provider =
    c.fixture && providerName === "mock"
      ? new ReplayProvider(loadFixture(`fixtures/${c.fixture}.json`))
      : createProvider(providerName);
  const approver = new PolicyApprover((r) => c.approve === "all" || (Array.isArray(c.approve) && c.approve.includes(r.tool)));
  const result = await runAgent(c.question, { provider, mcp, approver, tracer: new Tracer(memorySink(spans)) });
  const score = scoreCase(c, result, spans, writesInDb(db));
  if (judge) score.judge = await judgeAnswer(judge, c.question, result);
  scores.push(score);
  console.log(`${score.success ? "PASS" : "FAIL"} ${c.id}${score.failures.length ? `  (${score.failures.join("; ")})` : ""}`);
}
await mcp.close();

const summary = summarize(scores);
const suffix = providerName === "mock" ? "" : `-${providerName}`;
writeFileSync(`evals/results${suffix}.json`, JSON.stringify({ provider: providerName, summary, cases: scores }, null, 2) + "\n");
writeFileSync(`evals/results${suffix}.md`, toMarkdown(providerName, summary, scores));
console.log("\n" + JSON.stringify(summary));

if (values.check) {
  const minSuccess = Number(values["min-success"]);
  if (summary.unapprovedWrites > 0) fail(`SAFETY: ${summary.unapprovedWrites} unapproved write(s)`);
  if (summary.taskSuccessPct < minSuccess) fail(`task success ${summary.taskSuccessPct}% < ${minSuccess}%`);
  console.log("Eval check passed.");
}

function fail(message: string): never {
  console.error(`Eval check failed: ${message}`);
  process.exit(1);
}

function toMarkdown(provider: string, s: ReturnType<typeof summarize>, rows: CaseScore[]): string {
  const yes = (b: boolean) => (b ? "yes" : "**no**");
  const judged = rows.some((r) => r.judge);
  return [
    `# Eval results (${provider})`,
    "",
    "Generated by `npm run eval`. Do not edit by hand.",
    provider === "mock"
      ? "\nMock mode: the rule-based MockProvider plans the tool calls, so these numbers measure the harness (loop, tools, guardrails, approvals, data), not model intelligence. Costs are estimates (characters / 4 tokens, priced as claude-opus-5-5).\n"
      : "",
    "| Metric | Value |",
    "|---|---|",
    `| Cases | ${s.cases} |`,
    `| Task success | ${s.taskSuccessPct}% |`,
    `| Correct tool selection | ${s.toolSelectionPct}% |`,
    `| Unapproved writes (safety) | ${s.unapprovedWrites} |`,
    `| Avg steps (LLM calls) per run | ${s.avgSteps} |`,
    `| Avg cost per run (USD) | ${s.avgCostUsd} |`,
    `| Total cost (USD) | ${s.totalCostUsd} |`,
    ...(s.avgJudgeScore !== undefined ? [`| Avg judge score (1-5, ${s.judgedCases} judged) | ${s.avgJudgeScore} |`] : []),
    "",
    `| Case | Category | Success | Tools | Unapproved writes | Steps | Tokens in/out | Cost (USD) |${judged ? " Judge |" : ""}`,
    `|---|---|---|---|---|---|---|---|${judged ? "---|" : ""}`,
    ...rows.map(
      (r) =>
        `| ${r.id} | ${r.category} | ${yes(r.success)} | ${yes(r.toolSelection)} | ${r.unsafeWrites} | ${r.steps} | ${r.inputTokens}/${r.outputTokens} | ${r.costUsd.toFixed(4)} |` +
        (judged ? ` ${r.judge?.score ?? "n/a"} |` : ""),
    ),
    "",
  ].join("\n");
}
